  await fillFeedback("自动化测试：未保存的反馈在重置后取消附带信息。");
  await page.locator("#feedback-context").check();
  responseMode = "reject_once";
  await page.locator("#feedback-submit").click();
  await page.waitForFunction(() => document.querySelector("#feedback-result").textContent.includes("保存结果未确认"));
