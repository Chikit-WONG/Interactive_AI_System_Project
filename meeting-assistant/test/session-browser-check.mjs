  await page.locator('#user-responsibilities').fill('检查测试时间安排');
  await page.waitForFunction(() => document.querySelector('#role-save-state').textContent.includes('已保存'));
  await page.locator('#transcript-input').fill('主持人：这是隔离测试的一条发言。');
  await page.locator('#add-transcript').click();
  await page.waitForFunction(() => document.querySelector('#transcript-count').textContent === '1 条');
  const before = await state();
  await page.locator('#microphone-tab').click();
  await page.locator('#start-speech').click();
  await page.evaluate(() => { window.__oldResult = window.__testSpeech.onresult; });
  await page.locator('#auto-analyze').check();
  await page.locator('#stop-session').click();
  await page.waitForFunction(() => document.querySelector('#session-state').textContent === '会话已停止');
  const stopped = await state(), stoppedClock = await page.locator('#meeting-clock').textContent();
  assert.equal(stopped.meetingId, before.meetingId);
  assert.equal(stopped.utterances.length, 1);
  assert(stopped.session.elapsedMs > 0);
  assert.equal(await page.locator('#auto-analyze').isChecked(), false);
  assert.match(await page.locator('#monitor-input').textContent(), /未采集/);
  assert(await page.locator('#start-speech').isDisabled());
  assert(await page.locator('#system-audio-start').isDisabled());
  await page.evaluate(() => { const result = [{ transcript: '停止后迟到的假语音，不应保存' }]; result.isFinal = true; window.__oldResult({ resultIndex: 0, results: [result] }); });
  await page.waitForTimeout(4300);
  assert.equal(await page.locator('#meeting-clock').textContent(), stoppedClock);
  assert.equal(jobs.length, 0);
  assert.equal((await state()).utterances.length, 1);
  checks.push('Stop freezes time, preserves records, aborts microphone, cancels auto-analysis timer and ignores late speech');
  await page.locator('#feedback-open').click();
  assert(await page.locator('#feedback-dialog').evaluate(node => node.open));
  await page.locator('#feedback-close').click();
  const download = page.waitForEvent('download');
  await page.locator('#export-log').click();
  await (await download).saveAs(path.join(out, 'session-stopped-export-test.json'));
  checks.push('Feedback and export stay available while the session is stopped');
  await page.reload();
  await page.waitForFunction(() => document.querySelector('#session-state').textContent === '会话已停止');
  assert.equal(await page.locator('#meeting-clock').textContent(), stoppedClock);
  await page.locator('#start-session').click();
  await page.waitForFunction(() => document.querySelector('#session-state').textContent === '会话进行中');
  assert.equal((await state()).meetingId, before.meetingId);
  assert.equal(await page.evaluate(() => window.__speechStarts), 0);
  assert.equal(await page.locator('#auto-analyze').isChecked(), false);
  await page.waitForTimeout(1400);
  assert.notEqual(await page.locator('#meeting-clock').textContent(), stoppedClock);
  checks.push('Refresh preserves stopped state; continue preserves meeting and resumes only its active clock, not capture');
  await page.locator('#analyze-button').click();
  await page.waitForFunction(() => document.querySelector('#analyze-button').textContent.includes('正在分析'));
  while (!jobs.length) await new Promise(resolve => setTimeout(resolve, 15));
  await page.locator('#stop-session').click();
  await page.waitForFunction(() => document.querySelector('#session-state').textContent === '会话已停止');
  assert(jobs[0].signal.aborted);
  await page.locator('#start-session').click();
  await page.waitForFunction(() => document.querySelector('#session-state').textContent === '会话进行中');
  await page.locator('#analyze-button').click();
  await page.waitForSelector('.alert-card');
  jobs[0].resolve();
  await page.waitForTimeout(300);
  assert.equal((await state()).alerts.length, 1);
  assert.match((await state()).alerts[0].question, /测试提醒 1/);
  assert.equal(await page.locator('#analysis-error').isHidden(), true);
  checks.push('Stop aborts pending analysis; a resumed analysis survives the old late result without stale UI errors');
  await page.locator('#reset-meeting').click();
  await page.waitForFunction(() => document.querySelector('#session-state').textContent === '会话未开始');
  const fresh = await state();
  assert.notEqual(fresh.meetingId, before.meetingId);
  assert.equal(fresh.profile.name, '测试角色');
  assert.equal(fresh.utterances.length, 0);
  assert.equal(await page.locator('#meeting-clock').textContent(), '00:00');
  checks.push('New session confirms clearing, resets time to idle and retains profile');
  await page.locator('#replay-tab').click();
  await page.locator('#load-replay').click();
  await page.waitForFunction(() => document.querySelector('#user-name').value === '数据负责人');
  assert(await page.locator('#start-replay').isDisabled());
  await page.locator('#start-session').click();
  await page.locator('#start-replay').click();
  await page.waitForFunction(() => document.querySelector('#transcript-count').textContent === '1 条');
  await page.locator('#stop-session').click();
  await page.waitForFunction(() => document.querySelector('#session-state').textContent === '会话已停止');
  assert.match(await page.locator('#monitor-input').textContent(), /已暂停/);
  await page.locator('#start-session').click();
  assert(await page.locator('#stop-replay').isDisabled());
  await page.locator('#start-replay').click();
  await page.waitForTimeout(600);
  assert.equal((await state()).utterances.length, 1);
  await page.locator('#stop-session').click();
  checks.push('Stop pauses rehearsal, continue does not auto-play, and explicit replay resume does not duplicate prior text');
  // A response from a previous meeting must not overwrite a newer poll response.
  const oldMeeting = (await state()).meetingId;
  let releaseProfile, reachedProfile;
  const profileGate = new Promise(resolve => { releaseProfile = resolve; });
  const profileReached = new Promise(resolve => { reachedProfile = resolve; });
