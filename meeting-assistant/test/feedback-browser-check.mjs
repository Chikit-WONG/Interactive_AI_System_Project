const feedbackDirectory = await mkdtemp(path.join(out, "feedback-ui-test-fixture-"));
await writeFile(path.join(feedbackDirectory, "TEST_FIXTURE_ONLY.txt"), "Synthetic automated UI test records. Not participant feedback. Not the production feedback store.\n", "utf8");
