  assert.notEqual(posted.at(-1).submissionId, unsavedOldId);
  assert.equal(Object.hasOwn(posted.at(-1), "meetingId"), false);
  assert.equal(await count(), 6);
  checks.push("Unsaved stale-context retry stays editable and succeeds as new feedback after opting out of context");
  const downloadEvent = page.waitForEvent("download");
  await page.locator("#feedback-export").click();
  const download = await downloadEvent;
  const exportedPath = path.join(out, "feedback-export-test-fixture.json");
  await download.saveAs(exportedPath);
  const exportedText = await readFile(exportedPath, "utf8"), exported = JSON.parse(exportedText);
  assert.equal(exported.count, 6);
  assert.equal(exported.records.length, 6);
  assert.equal(exported.appVersion, APP_VERSION);
  assert(exported.records.every((record) => record.appVersion === APP_VERSION));
  assert.equal(exportedText.includes("秘密背景文本"), false);
  assert.equal(exportedText.includes("秘密会议原话"), false);
  checks.push("Feedback export downloads persisted records without meeting quotes or private background");
  // Hold a real save before it reaches the isolated store. Export must not
  // produce the old six-record snapshot while the seventh feedback is pending.
  await fillFeedback("自动化测试：保存与导出互斥，第七条反馈。");
  responseMode = "hold_once"; saveGate = deferred(); saveReached = deferred();
  await page.locator("#feedback-submit").click();
  await saveReached.promise;
  assert(await page.locator("#feedback-export").isDisabled());
  assert(await page.locator("#feedback-submit").isDisabled());
  const exportsBeforePending = exportRequests;
  await page.locator("#feedback-export").dispatchEvent("click");
  await page.waitForTimeout(100);
  assert.equal(exportRequests, exportsBeforePending);
  assert.equal(await count(), 6);
  assert.match(await page.locator("#feedback-result").textContent(), /^正在保存/);
  saveGate.resolve();
  await page.waitForFunction(() => document.querySelector("#feedback-result").textContent.includes("已保存在"));
  assert.equal(await count(), 7);
  await fillFeedback("自动化测试：导出期间不能提交的未保存草稿。");
  exportMode = "hold_once"; exportGate = deferred(); exportReached = deferred();
  const concurrentDownload = page.waitForEvent("download");
  concurrentDownload.catch(() => {}); // Avoid masking an earlier assertion on cleanup.
  await page.locator("#feedback-export").click();
  await exportReached.promise;
  assert(await page.locator("#feedback-fields").evaluate((node) => node.disabled));
  assert(await page.locator("#feedback-message").isDisabled());
  assert(await page.locator("#feedback-submit").isDisabled());
