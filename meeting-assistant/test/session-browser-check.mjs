  for (const id of ['stop-session', 'add-transcript', 'analyze-button', 'auto-analyze', 'start-speech', 'system-audio-start']) assert(await page.locator(`#${id}`).isDisabled(), id);
  assert.equal((await state()).startedAt, null);
  checks.push('New session stays idle at 00:00; capture, input and analysis require explicit start');
  await page.screenshot({ path: path.join(out, 'session-01-idle-test.png'), fullPage: true });
  await page.locator('#start-session').click();
  await page.waitForFunction(() => document.querySelector('#session-state').textContent === '会话进行中');
